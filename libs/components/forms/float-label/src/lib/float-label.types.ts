/**
 * `over` — the label sits over the field at rest and floats up to overlap the
 * top border when the field is focused or filled (the classic Material style).
 * `in`  — the label floats to a small size *inside* the field's top padding.
 * `on`  — the label floats onto the border with a background chip cutting it.
 */
export type DynamoFloatLabelVariant = 'over' | 'in' | 'on';

export type DynamoFloatLabelPart = 'root' | 'label';
